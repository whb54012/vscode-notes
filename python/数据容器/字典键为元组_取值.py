# 字典的键是元组，怎么取？

d = {
    (1, 2): "位置A",
    (3, 4): "位置B",
    (5, 6): "位置C"
}

# ============ 1. 直接拿键对应的值 ============
print(d[(1, 2)])   # 位置A
print(d[(3, 4)])   # 位置B

# ============ 2. 拿到键，再取键里的元素 ============
# 先拿所有键
keys = list(d.keys())     # [(1, 2), (3, 4), (5, 6)]
print(keys[0])            # (1, 2)
print(keys[0][0])         # 1  ← 元组第一个元素
print(keys[0][1])         # 2  ← 元组第二个元素

# ============ 3. 遍历取键里的元素 ============
for key in d:
    print(key)            # (1, 2) \n (3, 4) \n (5, 6)
    print(key[0])         # 1 \n 3 \n 5
    print(key[1])         # 2 \n 4 \n 6

# ============ 4. 键和值一起遍历 ============
for key, val in d.items():
    print(f"键是{key}，第一个元素是{key[0]}，第二个元素是{key[1]}，对应的值是{val}")

# ============ 5. 按条件查 ============
# 找键里第一个元素是 1 或 3 的值
for key in d:
    if key[0] == 1:
        print(d[key])     # 位置A
    elif key[0] == 3:
        print(d[key])     # 位置B

# ============ 6. 更多元素的元组键 ============
d2 = {
    (1, 2, 3): "三维",
    (4, 5, 6): "三维2"
}
for key in d2:
    print(key[0], key[1], key[2])   # 1 2 3 \n 4 5 6
