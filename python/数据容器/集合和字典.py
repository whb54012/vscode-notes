#                          3.集合
#用{}包裹，打印无序且去除跳过重复部分
a = {'123',"123","我爱你","我恨你"}#单双引号可自由替换
print(a)
# 因为无序,所以没有索引
s=set()
#不可直接写成{},{}为空字典
a.add('t')#末尾添加
a.remove('t')#移除指定元素,移除一个
a.pop()#随意移除一个
a.clear()#清空集合
a.difference(s)#求取两个集合的不同值
#
#打印整体不会打印括号

