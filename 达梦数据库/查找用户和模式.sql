达梦查找模式
SELECT NAME FROM SYS.SYSOBJECTS;
-- SYS.SYSOBJECTS:当前数据库的所有对象,包括用户,模式,表
SELECT NAME,ID FROM SYS.SYSOBJECTS WHERE TYPE$ = 'SCH';
-- 只筛选【类型是模式】的对象，只列出模式名和他的schid（精准）
SELECT TABLE_NAME FROM SYS.USER_TABLES;
-- 查找当前所属用户的所有表
SELECT NAME FROM SYS.SYSTABLES WHERE SCHID=CURRENT_SCHID;
-- 查看当前模式所有表
SELECT NAME FROM SYS.systables WHERE SCHID=(SELECT ID FROM SYS.SYSOBJECTS WHERE TYPE$ = 'SCH' AND NAME='模式名');
-- 查找指定模式名下的所有表格
SELECT NAME FROM SYS.SYSCOLUMNS WHERE ID=(SELECT ID FROM SYS.systables where NAME='表名' AND SCHID='模式id');
-- 查找指定表名的所有字段名

